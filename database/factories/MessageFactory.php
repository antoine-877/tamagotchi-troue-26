/**
 * @extends Factory<Message>
 */
class MessageFactory extends Factory
{
    /**
     * @return array<string, mixed>
     */
    public function definition(): array
    {
        return [
            'author_id' => User::factory(),
            'recipient_id' => User::factory(),
            'body' => fake()->sentence(),
        ];
    }
}
